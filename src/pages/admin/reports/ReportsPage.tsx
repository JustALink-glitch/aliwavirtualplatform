type Kind = 'cohort_summary' | 'programme_summary' | 'attendance' | 'assignments' | 'feedback'
type Format = 'pdf' | 'csv'

interface Report {
  id: string
  kind: Kind
  title: string
  subtitle: string | null
  format: Format
  status: 'queued' | 'running' | 'ready' | 'failed' | 'expired'
  by: { id: string; name: string } | null
  createdAt: string
  completedAt: string | null
}

const kinds: { value: Kind; label: string; description: string; cohort: 'required' | 'optional' | 'none' }[] = [
  {
    value: 'cohort_summary',
    label: 'Cohort summary',
    description: 'Enrolment, attendance, assignment completion, feedback and Needs attention for one cohort.',
    cohort: 'required',
  },
  { value: 'programme_summary', label: 'Programme summary', description: 'The same measures across every cohort in a programme.', cohort: 'none' },
  { value: 'attendance', label: 'Attendance', description: 'Session-by-session attendance with present, excused and absent counts.', cohort: 'required' },
  { value: 'assignments', label: 'Assignments and grades', description: 'Submission and grading status per assignment.', cohort: 'required' },
  { value: 'feedback', label: 'Feedback', description: 'Post-session feedback, aggregated by session and trainer.', cohort: 'optional' },
]

type Filter = 'all' | 'summaries' | 'attendance' | 'assignments' | 'feedback'
const filterOf = (k: Kind): Filter => (k === 'cohort_summary' || k === 'programme_summary' ? 'summaries' : k)

const columns: Column[] = [
  { label: 'Report' },
  { label: 'Format', width: 80, hideBelow: 'lg' },
  { label: 'Generated by', width: 190, hideBelow: 'lg' },
  { label: 'Generated', width: 170 },
  { label: '', width: 110, align: 'right' },
]

const keys = { all: ['reports-export'] as const }

/** /admin/reports — E1.01 Reports, E1.01e empty, E1.03 generating, E1.04 ready, E1.05 failed. */
export function ReportsPage() {
  const client = useQueryClient()
  const query = useQuery({
    queryKey: keys.all,
    queryFn: ({ signal }) => api<{ timeZone: string; reports: Report[] }>('/v1/reports', { signal }),
    // Check again while something is being generated.
    refetchInterval: (q) => (q.state.data?.reports.some((r) => r.status === 'queued' || r.status === 'running') ? 2000 : false),
  })
  const [params, setParams] = useSearchParams()
  const [generating, setGenerating] = useState(params.get('generate') === '1')
  const [latest, setLatest] = useState<string | null>(null)
  const [filter, setFilter] = useState<Filter>('all')
  const [search, setSearch] = useState('')
  const [page, setPage] = useState(1)
  const retry = useMutation({
    mutationFn: (id: string) => api<{ report: { id: string } }>(`/v1/reports/${id}/retry`, { method: 'POST', body: {} }),
    onSuccess: (data) => {
      setLatest(data.report.id)
      void client.invalidateQueries({ queryKey: keys.all })
    },
  })

  const reports = query.data?.reports ?? []
  const timeZone = query.data?.timeZone
  const term = search.trim().toLowerCase()
  const visible = reports.filter((r) => (filter === 'all' || filterOf(r.kind) === filter) && (!term || r.title.toLowerCase().includes(term)))
  const paged = paginate(visible, page)
  const count = (f: Filter) => reports.filter((r) => filterOf(r.kind) === f).length
  const current = latest ? reports.find((r) => r.id === latest) : undefined

  return (
    <>
      <PageHeader
        title="Reports"
        description="Built from data already captured in Synqop, with the same definitions as the dashboard."
        actions={
          <Button icon={<FileIcon size={16} />} onClick={() => setGenerating(true)}>
            Generate report
          </Button>
        }
      />
      {current && (current.status === 'queued' || current.status === 'running') && (
        <AlertBanner tone="info" title={`Generating ${current.title}`}>
          Usually under a minute. You can leave this page; it will be in this list when it’s ready.
        </AlertBanner>
      )}
      {current?.status === 'ready' && (
        <AlertBanner tone="success" title={`${current.title} is ready`}>
          <button type="button" className="text-brand-text underline" onClick={() => void download(current)}>
            Download {current.format.toUpperCase()}
          </button>
        </AlertBanner>
      )}
      {current?.status === 'failed' && (
        <AlertBanner tone="error" title={`Couldn’t generate ${current.title}`}>
          Something went wrong on our side and nothing was exported. Try again; if it keeps failing, contact support.
        </AlertBanner>
      )}
      {query.isPending ? (
        <Panel aria-busy="true" aria-label="Loading reports" className="h-[240px]">
          <span className="sr-only">Loading reports</span>
        </Panel>
      ) : query.isError ? (
        <Panel>
          <StatePanel
            kind="error"
            title="Couldn’t load reports"
            description="Check your connection and try again."
            action={{ label: 'Try again', onClick: () => void query.refetch() }}
          />
        </Panel>
      ) : reports.length === 0 ? (
        <Panel className="py-12">
          <EmptyState
            icon={<ChartIcon size={24} />}
            title="No reports yet"
            body="Generate a cohort or programme summary, attendance, assignments or feedback report as a PDF or CSV. Everything comes from data already in Synqop."
            actions={<Button onClick={() => setGenerating(true)}>Generate report</Button>}
          />
        </Panel>
      ) : (
        <>
          <div className="flex items-center gap-3 max-md:flex-col max-md:items-stretch">
            <FilterChips
              label="Report type"
              value={filter}
              onChange={(f) => {
                setFilter(f)
                setPage(1)
              }}
              options={[
                { value: 'all', label: 'All', count: reports.length },
                ...(['summaries', 'attendance', 'assignments', 'feedback'] as const)
                  .filter((f) => count(f) > 0)
                  .map((f) => ({ value: f, label: f === 'summaries' ? 'Summaries' : f.charAt(0).toUpperCase() + f.slice(1), count: count(f) })),
              ]}
            />
            <div className="flex-1" />
            <SearchField
              aria-label="Search reports"
              placeholder="Search reports"
              value={search}
              onChange={(e) => {
                setSearch(e.target.value)
                setPage(1)
              }}
            />
          </div>
          <Panel className="gap-0 max-md:py-2">
            <h2 className="pb-2 text-heading-section text-primary max-md:hidden">Generated reports</h2>
            {visible.length === 0 ? (
              <p role="status" className="p-8 text-center text-body text-secondary">
                No reports match.
              </p>
            ) : (
              <>
                <div className="max-md:hidden">
                  <Table columns={columns}>
                    {paged.rows.map((r) => (
                      <Row key={r.id}>
                        <Cell>
                          <Stacked primary={r.title} secondary={r.subtitle ?? undefined} />
                        </Cell>
                        <Cell hideBelow="lg">{r.format.toUpperCase()}</Cell>
                        <Cell hideBelow="lg">
                          {r.by ? (
                            <span className="flex min-w-0 items-center gap-2">
                              <Avatar initials={initials(r.by.name)} seed={r.by.id} />
                              <span className="truncate text-body-strong text-primary">{r.by.name}</span>
                            </span>
                          ) : (
                            <span className="text-muted">—</span>
                          )}
                        </Cell>
                        <Cell className="tabular-nums">
                          <When report={r} timeZone={timeZone} />
                        </Cell>
                        <Cell align="right">
                          <ReportAction report={r} onRetry={() => retry.mutate(r.id)} retrying={retry.isPending && retry.variables === r.id} />
                        </Cell>
                      </Row>
                    ))}
                  </Table>
                </div>
                <ul className="md:hidden">
                  {paged.rows.map((r) => (
                    <li key={r.id} className="flex items-center gap-3 border-b border-default py-3 last:border-b-0">
                      <span className="flex min-w-0 flex-1 flex-col gap-0.5">
                        <span className="truncate text-body-strong text-primary">{r.title}</span>
                        <span className="truncate text-caption text-secondary">{[r.subtitle, r.format.toUpperCase()].filter(Boolean).join(' · ')}</span>
                        <span className="text-caption text-secondary">
                          <When report={r} timeZone={timeZone} />
                        </span>
                      </span>
                      <ReportAction report={r} onRetry={() => retry.mutate(r.id)} retrying={retry.isPending && retry.variables === r.id} />
                    </li>
                  ))}
                </ul>
              </>
            )}
            <TableFooter summary={plural(visible.length, 'report')} page={paged.page} pageCount={paged.pageCount} onPage={setPage} />
          </Panel>
        </>
      )}
      {generating && (
        <GenerateReportDialog
          onClose={() => {
            setGenerating(false)
            if (params.has('generate')) setParams({}, { replace: true })
          }}
          onStarted={(id) => {
            setGenerating(false)
            if (params.has('generate')) setParams({}, { replace: true })
            setLatest(id)
            void client.invalidateQueries({ queryKey: keys.all })
          }}
        />
      )}
    </>
  )
}

function When({ report: r, timeZone }: { report: Report; timeZone: string | undefined }) {
  if (r.status === 'queued' || r.status === 'running') return <span className="text-secondary">Generating…</span>
  if (r.status === 'failed') return <span className="text-error-fg">Failed · {stamp(r.completedAt ?? r.createdAt, timeZone)}</span>
  if (r.status === 'expired') return <span className="text-muted">Expired</span>
  return <>{stamp(r.completedAt ?? r.createdAt, timeZone)}</>
}

const stamp = (at: string, timeZone: string | undefined) => `${formatDay(at, timeZone)}, ${formatTime(at, timeZone)}`

async function download(r: Report) {
  await downloadApiFile(`/v1/reports/${r.id}/file`, `${r.title.replace(/\s*[—–]\s*/g, ' - ').replace(/[\\/:*?"<>|]+/g, '')}.${r.format}`)
}

function ReportAction({ report: r, onRetry, retrying }: { report: Report; onRetry: () => void; retrying: boolean }) {
  const [failed, setFailed] = useState(false)
  const style =
    'inline-flex h-9 items-center gap-1 text-caption-strong text-brand-text hover:underline focus-visible:underline focus-visible:outline-none disabled:opacity-50'
  if (r.status === 'failed') {
    return (
      <button type="button" className={style} onClick={onRetry} disabled={retrying}>
        {retrying ? 'Starting…' : 'Try again'}
        <ChevronRightIcon size={14} />
      </button>
    )
  }
  if (r.status !== 'ready') return null
  return (
    <button
      type="button"
      className={clsx(style, failed && 'text-error-fg')}
      onClick={async () => {
        setFailed(false)
        try {
          await download(r)
        } catch {
          setFailed(true)
        }
      }}
    >
      {failed ? 'Try again' : 'Download'}
      <DownloadIcon size={14} />
    </button>
  )
}

/** E1.02 Generate report. */
export function GenerateReportDialog({ onClose, onStarted }: { onClose: () => void; onStarted: (id: string) => void }) {
  const { state } = useAuth()
  const timeZone = state.status === 'signed-in' ? state.me.organisation?.timeZone : undefined
  const programmes = useProgrammes()
  const cohorts = useCohorts()
  const [kind, setKind] = useState<Kind>('cohort_summary')
  const [programmeId, setProgrammeId] = useState('')
  const [cohortId, setCohortId] = useState('')
  const [from, setFrom] = useState('')
  const [to, setTo] = useState('')
  const [format, setFormat] = useState<Format>('pdf')
  const [errors, setErrors] = useState<Record<string, string>>({})
  const [failed, setFailed] = useState<string | null>(null)
  const start = useMutation({ mutationFn: (body: unknown) => api<{ report: { id: string } }>('/v1/reports', { method: 'POST', body }) })

  const programmeList = (programmes.data?.programmes ?? []).filter((p) => p.status !== 'archived')
  const programme = programmeId || programmeList[0]?.id || ''
  const cohortList = (cohorts.data ?? []).filter((c) => c.programme.id === programme && c.status !== 'draft')
  const spec = kinds.find((k) => k.value === kind)!
  const cohort = spec.cohort === 'none' ? '' : cohortId || (spec.cohort === 'required' ? (cohortList[0]?.id ?? '') : '')
  const selected = cohortList.find((c) => c.id === cohort)
  // Default period: the cohort's dates up to today, or nothing (programme to date).
  const today = todayIn(timeZone)
  const effectiveFrom = from || selected?.startsOn || ''
  const effectiveTo = to || (selected ? (selected.endsOn < today ? selected.endsOn : today) : '')

  async function onSubmit(event: FormEvent) {
    event.preventDefault()
    setErrors({})
    setFailed(null)
    try {
      const result = await start.mutateAsync({
        kind,
        programmeId: programme,
        cohortId: cohort || null,
        from: effectiveFrom || null,
        to: effectiveTo || null,
        format,
      })
      onStarted(result.report.id)
    } catch (error) {
      if (error instanceof ApiError && Array.isArray(error.details))
        setErrors(Object.fromEntries((error.details as { field: string; message: string }[]).map((d) => [d.field, d.message])))
      else setFailed(error instanceof ApiError && error.status < 500 ? error.message : 'It didn’t start. Try again.')
    }
  }

  return (
    <Dialog
      open
      onClose={() => !start.isPending && onClose()}
      title="Generate report"
      description="Built from data already captured in Synqop, using the same definitions as the dashboard."
      actions={
        <>
          <span className="mr-auto self-center text-caption text-secondary max-md:hidden">Admins only. Exports are logged.</span>
          <Button variant="secondary" onClick={onClose} disabled={start.isPending}>
            Cancel
          </Button>
          <Button type="submit" form="generate-report" icon={<DownloadIcon size={16} />} disabled={start.isPending || !programme}>
            {start.isPending ? 'Starting…' : 'Generate report'}
          </Button>
        </>
      }
    >
      <form id="generate-report" onSubmit={onSubmit} noValidate className="flex flex-col gap-4">
        {failed && <AlertBanner tone="error" title={failed} />}
        {programmes.data && programmeList.length === 0 && (
          <AlertBanner tone="info" title="Create a programme first">
            Reports are built from programmes and their cohorts.
          </AlertBanner>
        )}
        <fieldset className="flex flex-col gap-2">
          <legend className="pb-2 text-caption-strong text-primary">Report</legend>
          {kinds.map((k) => (
            <label
              key={k.value}
              className={clsx(
                'flex cursor-pointer items-start gap-3 rounded-md border p-3 transition-colors',
                kind === k.value ? 'border-brand bg-brand-subtle' : 'border-default bg-surface hover:bg-surface-hover',
              )}
            >
              <input
                type="radio"
                name="kind"
                checked={kind === k.value}
                onChange={() => {
                  setKind(k.value)
                  setCohortId('')
                }}
                className="mt-0.5 size-4 shrink-0 cursor-pointer appearance-none rounded-full border border-strong bg-surface checked:border-[5px] checked:border-brand focus-visible:shadow-[var(--shadow-focus)] focus-visible:outline-none"
              />
              <span className="flex flex-col gap-0.5">
                <span className="text-body-strong text-primary">{k.label}</span>
                <span className="text-caption text-secondary">{k.description}</span>
              </span>
            </label>
          ))}
        </fieldset>
        <div className="grid grid-cols-2 gap-3 max-md:grid-cols-1">
          <SelectField
            label="Programme"
            value={programme}
            onChange={(e) => {
              setProgrammeId(e.target.value)
              setCohortId('')
            }}
            error={errors.programmeId}
          >
            {programmeList.map((p) => (
              <option key={p.id} value={p.id}>
                {p.name}
              </option>
            ))}
          </SelectField>
          {spec.cohort !== 'none' && (
            <SelectField label="Cohort" value={cohort} onChange={(e) => setCohortId(e.target.value)} error={errors.cohortId}>
              {spec.cohort === 'optional' && <option value="">All cohorts</option>}
              {spec.cohort === 'required' && cohortList.length === 0 && <option value="">No cohorts yet</option>}
              {cohortList.map((c) => (
                <option key={c.id} value={c.id}>
                  {c.name}
                </option>
              ))}
            </SelectField>
          )}
          <TextField label="From" optional type="date" value={effectiveFrom} onChange={(e) => setFrom(e.target.value)} error={errors.from} />
          <TextField label="To" optional type="date" value={effectiveTo} onChange={(e) => setTo(e.target.value)} error={errors.to} />
        </div>
        <fieldset className="flex flex-col gap-2">
          <legend className="pb-2 text-caption-strong text-primary">Format</legend>
          <div className="flex gap-6">
            {(
              [
                ['pdf', 'PDF report'],
                ['csv', 'CSV data'],
              ] as const
            ).map(([v, l]) => (
              <label key={v} className="inline-flex cursor-pointer items-center gap-2 text-body text-primary">
                <input
                  type="radio"
                  name="format"
                  checked={format === v}
                  onChange={() => setFormat(v)}
                  className="size-4 shrink-0 cursor-pointer appearance-none rounded-full border border-strong bg-surface checked:border-[5px] checked:border-brand focus-visible:shadow-[var(--shadow-focus)] focus-visible:outline-none"
                />
                {l}
              </label>
            ))}
          </div>
        </fieldset>
      </form>
    </Dialog>
  )
}
